const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync(`${__dirname}/native_boot.js`, 'utf8');
let disk = JSON.stringify({level:{player:{exp:0,level:1,diamond:137},units:[],user_config:{rookie0:123}},receipt:true});
let writes = 0;
const ctx = {LocalNative:{readRaw:()=>JSON.parse(disk),writeRaw:s=>{disk=JSON.stringify(s);writes++;},writeStatus(){}},
    G_Player:null,GS_CURRENT_STAGE:'battle',GS_STAGE_BUILD:'home'};
vm.createContext(ctx);
const start=source.indexOf('        LocalNative.copyAccountProgress = function');
const end=source.indexOf('        LocalNative.tryDumpAndSave = function',start);
vm.runInContext(source.slice(start,end),ctx);
// Keep gameplay calculation owned by the client; test persistence after it returns.
const proto={addExp(amount){this.exp+=amount;while(this.exp>=100){this.exp-=100;this.level++;}return 'stock';}};
const stock=fs.readFileSync(`${__dirname}/disasm/ClientPlayer.decompiled.js`,'utf8');
const a=stock.indexOf('ClientPlayer.prototype.rpc_c_refresh_player_info=');
const b=stock.indexOf('ClientPlayer.prototype.rpc_c_add_player_exp=',a);
ctx.ClientPlayer={prototype:proto};
vm.runInContext(stock.slice(a,b),ctx);
ctx.LocalNative.installAccountProgressPersistence(proto);
ctx.LocalNative.installAccountProgressPersistence(proto);
const player=Object.assign(Object.create(proto),{exp:0,level:1,refreshUI(){}});
ctx.G_Player=player;
assert.equal(player.addExp(65),'stock');
assert.equal(JSON.parse(disk).level.player.exp,65);
assert.equal(writes,1,'hook installation is idempotent');
player.addExp(55);
assert.deepEqual(JSON.parse(disk).level.player,{exp:20,level:2,diamond:137});
// Recreate the player from serialized login fields, then earn more after restart.
const restarted=Object.assign(Object.create(proto),JSON.parse(disk).level.player,{refreshUI(){}});
ctx.G_Player=restarted;
restarted.addExp(7);
assert.equal(JSON.parse(disk).level.player.exp,27);
restarted.rpc_c_refresh_player_info({exp:0,level:3});
assert.equal(JSON.parse(disk).level.player.exp,0,'zero experience after leveling is saved');
assert.equal(JSON.parse(disk).level.player.level,3);
player.addExp(500);
assert.equal(JSON.parse(disk).level.player.level,3,'other player cannot overwrite account');
const good=disk;
restarted.exp=NaN;restarted.addExp(1);
assert.equal(disk,good,'invalid progress cannot corrupt the save');
assert.equal(JSON.parse(disk).receipt,true);
assert.equal(JSON.parse(disk).level.user_config.rookie0,123);
const snapshotStart=source.indexOf('        LocalNative.tryDumpAndSave = function');
const snapshotEnd=source.indexOf('        // After bunker gem-finish',snapshotStart);
vm.runInContext(source.slice(snapshotStart,snapshotEnd),ctx);
ctx.LocalNative.getBuildController=()=>({});
ctx.LocalNative.collectHomeBuildings=()=>[];
ctx.LocalNative.getResourceManager=()=>null;
ctx.LocalNative.saveLevel=level=>{const saved=JSON.parse(disk);saved.level=level;disk=JSON.stringify(saved);};
ctx.GS_CURRENT_STAGE='home';
restarted.exp=19;restarted.level=4;
assert.equal(ctx.LocalNative.tryDumpAndSave(),true);
assert.equal(JSON.parse(disk).level.player.exp,19);
assert.equal(JSON.parse(disk).level.player.level,4);
ctx.GS_CURRENT_STAGE='battle';
restarted.exp=99;
assert.equal(ctx.LocalNative.tryDumpAndSave(),false);
assert.equal(JSON.parse(disk).level.player.exp,19,'battle snapshot remains blocked');
assert.ok(source.includes('LocalNative.copyAccountProgress(level.player, G_Player);'));
assert.ok(source.includes('LocalNative.installAccountProgressPersistence(cpp);'));
console.log('PASS: immediate account XP/level persistence, restart, level-up, zero XP, stock refresh RPC, player isolation and invalid-value protection');
