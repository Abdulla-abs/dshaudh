const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(`${__dirname}/native_boot.js`,'utf8');
const ctx={LocalNative:{},data:{}};
vm.createContext(ctx);
for(const name of ['hero_lv_data','hero_number'])
    vm.runInContext(fs.readFileSync(`${__dirname}/../.local/hero-exp/${name}.js`,'utf8'),ctx);
const a=source.indexOf('        LocalNative.normalizeHeroExperience = function');
const b=source.indexOf('        LocalNative.ensureHeroSkill = function',a);
vm.runInContext(source.slice(a,b),ctx);
const n=ctx.LocalNative;
const level={units:[{typeid:20602}]};
const hero={lv:1,xp:17,typeid:11306,skill_slots:[{sid:7093,lv:1}]};
n.normalizeHeroExperience(level,hero,0);
assert.equal(hero.lv,2);assert.equal(hero.level,2);assert.equal(hero.xp,14);
assert.equal(hero.typeid,11306);assert.equal(hero.skill_slots[0].sid,7093);
assert.equal(n.normalizeHeroExperience(level,hero,0),false,'load repair idempotent');
n.normalizeHeroExperience(level,hero,1);
assert.equal(hero.lv,3);assert.equal(hero.xp,0,'exact threshold');
const many={lv:1,xp:0};
n.normalizeHeroExperience(level,many,33);
assert.equal(many.lv,4);assert.equal(many.xp,0,'multiple levels');
const cap={lv:19,xp:0};
n.normalizeHeroExperience(level,cap,999999);
assert.equal(cap.lv,20);assert.equal(cap.xp,ctx.data.hero_lv_data[20].hero_exp);
const gift={lv:30,xp:0};
n.normalizeHeroExperience(level,gift,0);
assert.equal(gift.lv,30,'keep existing gift above nest cap');
const legacy={level:1,xp:7};
n.normalizeHeroExperience(level,legacy,0);
assert.equal(legacy.lv,2);assert.equal(legacy.xp,4);
const restart=JSON.parse(JSON.stringify(hero));
assert.equal(n.normalizeHeroExperience(level,restart,0),false);
assert.equal(restart.lv,3);
console.log('PASS: 17/3 -> level 2 with 14/15; exact/multiple thresholds, nest cap, gift preservation and restart idempotency');
